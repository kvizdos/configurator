package terraform

import (
	"testing"

	"github.com/kvizdos/configurator/internal/core"
)

func TestRender(t *testing.T) {
	r, err := New("aws", "/configurator/name/")
	if err != nil {
		t.Fatal(err)
	}
	out, err := r.Render([]core.Variable{
		{Key: "db_host", Value: "h"},
		{Key: "db_password", Value: "p", Sensitive: true},
	})
	if err != nil {
		t.Fatal(err)
	}

	want := `# Code generated by configurator. DO NOT EDIT.
# Reference the locals below rather than the data sources directly.

data "aws_ssm_parameter" "configurator_db_host" {
  name = "/configurator/name/db_host"
}

data "aws_ssm_parameter" "configurator_db_password" {
  name            = "/configurator/name/db_password"
  with_decryption = true
}

locals {
  configurator_db_host     = data.aws_ssm_parameter.configurator_db_host.value
  configurator_db_password = sensitive(data.aws_ssm_parameter.configurator_db_password.value)
}
`
	if string(out) != want {
		t.Fatalf("got:\n%s\nwant:\n%s", out, want)
	}
}

func TestRenderEmpty(t *testing.T) {
	r, _ := New("aws", "/x")
	out, err := r.Render(nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(out) == 0 {
		t.Fatal("expected header even with no variables")
	}
}

func TestNewUnsupportedProvider(t *testing.T) {
	if _, err := New("gcp", "/x"); err == nil {
		t.Fatal("expected error for unsupported provider")
	}
}
