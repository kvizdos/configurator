// Package terraform renders variables as a configurator.tf file: one data
// source per variable plus a `locals` block that the rest of the Terraform
// code should reference, so the storage provider can be swapped freely.
package terraform

import (
	"fmt"
	"strings"

	"github.com/kvizdos/configurator/internal/core"
)

const FileName = "configurator.tf"

type Renderer struct {
	basePath string
}

var _ core.Renderer = (*Renderer)(nil)

// New returns a Renderer for the given storage provider. Only "aws" (SSM)
// is currently supported.
func New(provider, basePath string) (*Renderer, error) {
	if provider != "aws" {
		return nil, fmt.Errorf("terraform output does not support provider %q", provider)
	}
	return &Renderer{basePath: strings.TrimRight(basePath, "/")}, nil
}

// Render expects vars sorted by key; output is formatted to match
// `terraform fmt`.
func (r *Renderer) Render(vars []core.Variable) ([]byte, error) {
	var b strings.Builder
	b.WriteString("# Code generated by configurator. DO NOT EDIT.\n")
	b.WriteString("# Reference the locals below rather than the data sources directly.\n")

	for _, v := range vars {
		name := identifier(v.Key)
		fmt.Fprintf(&b, "\ndata \"aws_ssm_parameter\" %q {\n", name)
		if v.Sensitive {
			fmt.Fprintf(&b, "  name            = %q\n", r.basePath+"/"+v.Key)
			b.WriteString("  with_decryption = true\n")
		} else {
			fmt.Fprintf(&b, "  name = %q\n", r.basePath+"/"+v.Key)
		}
		b.WriteString("}\n")
	}

	if len(vars) == 0 {
		return []byte(b.String()), nil
	}

	width := 0
	for _, v := range vars {
		width = max(width, len(identifier(v.Key)))
	}
	b.WriteString("\nlocals {\n")
	for _, v := range vars {
		name := identifier(v.Key)
		ref := fmt.Sprintf("data.aws_ssm_parameter.%s.value", name)
		if v.Sensitive {
			ref = "sensitive(" + ref + ")"
		}
		fmt.Fprintf(&b, "  %-*s = %s\n", width, name, ref)
	}
	b.WriteString("}\n")

	return []byte(b.String()), nil
}

func identifier(key string) string {
	return "configurator_" + key
}
